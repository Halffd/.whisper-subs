"""YouTube caption extraction: human-made and automatic captions.

Extracted from the inline block that used to live in `whisper_subs.py`
(which only ever handled human-made subs and gave up otherwise).

Two caption flavours exist on YouTube and they are *not* equivalent:

- **human** (`info["subtitles"]`): uploaded by the creator/community.
  Always usable output — this is what the tool wants by default.
- **auto** (`info["automatic_captions"]`): machine-generated by YouTube.
  Quality varies wildly and the language list is far larger; useful only
  when the user asks for it explicitly.

`fetch_captions()` returns a `CaptionResult` describing what was written
(or why nothing was), so callers can fall back to transcription instead
of guessing from the filesystem.
"""

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

import yt_dlp


# Preference order for picking a caption track when the user has not
# restricted languages. English first (most videos that have human subs
# have them in English), then the original language of the video.
DEFAULT_LANG_PRIORITY = ("en", "es", "pt", "fr", "de", "it", "ja")


@dataclass
class CaptionTrack:
    """One subtitle track as yt-dlp reports it."""

    lang: str
    url: str
    ext: str
    is_automatic: bool
    name: str = ""

    @classmethod
    def from_entry(
        cls,
        lang: str,
        entry: Dict[str, Any],
        automatic: Optional[bool] = None,
    ) -> "CaptionTrack":
        """Build a track from one yt-dlp caption entry.

        `automatic` says which dict the entry came from. It must be passed
        explicitly: yt-dlp omits ``is_automatic`` entirely on both human
        entries *and* ASR-origins (``en-orig``), so the field alone cannot
        tell a machine track from an uploaded one — an ASR-only video would
        otherwise report its machine captions as human.
        """
        if automatic is None:
            automatic = bool(entry.get("is_automatic", False))
        return cls(
            lang=lang,
            url=entry.get("url", ""),
            ext=entry.get("ext", ""),
            is_automatic=automatic,
            name=entry.get("name", "") or "",
        )


@dataclass
class CaptionResult:
    """Outcome of a caption fetch attempt."""

    ok: bool = False
    path: Optional[str] = None
    lang: Optional[str] = None
    automatic: bool = False
    # Human-readable reason, always set when ok is False.
    reason: str = ""
    # Every candidate track found, for UI/diagnostics.
    available: List[CaptionTrack] = field(default_factory=list)


def _base_opts() -> Dict[str, Any]:
    """Metadata-only yt-dlp options: no media download, no side effects."""
    return {
        "quiet": True,
        "no_warnings": True,
        "skip_download": True,
        "noprogress": True,
    }


def _tracks_from_info(info: Dict[str, Any]) -> List[CaptionTrack]:
    """Every track yt-dlp reported, tagged human/automatic by its dict.

    The tag comes from the section the entries live in, never from
    ``is_automatic`` on the entry: yt-dlp omits that key for uploaded tracks
    *and* for ASR-origins (``en-orig``), so only the section is reliable.
    """
    tracks: List[CaptionTrack] = []
    for lang, entries in (info.get("subtitles") or {}).items():
        tracks.extend(
            CaptionTrack.from_entry(lang, e, automatic=False)
            for e in entries or []
        )
    for lang, entries in (info.get("automatic_captions") or {}).items():
        tracks.extend(
            CaptionTrack.from_entry(lang, e, automatic=True)
            for e in entries or []
        )
    return tracks


def list_captions(url: str) -> List[CaptionTrack]:
    """All caption tracks for `url`, human and automatic, or [] on failure."""
    try:
        with yt_dlp.YoutubeDL(_base_opts()) as ydl:
            info = ydl.extract_info(url, download=False)
    except Exception:
        return []
    if not info:
        return []
    return _tracks_from_info(info)

def has_human_captions(url: str) -> bool:
    """True when at least one human-uploaded track exists."""
    return any(
        not t.is_automatic for t in list_captions(url)
    )


def _pick_track(
    tracks: List[CaptionTrack],
    langs: Optional[List[str]],
    allow_automatic: bool,
    video_lang: Optional[str],
) -> Optional[CaptionTrack]:
    """Choose the best track given language preferences.

    Preference order, first match wins:
      1. an explicitly requested language,
      2. the video's own original language,
      3. DEFAULT_LANG_PRIORITY.

    Language matching is region-tolerant: `pt` matches `pt-BR` (and
    `pt-BR` matches a bare `pt` request), because YouTube labels the same
    original track either way depending on uploader.

    Human tracks always beat automatic ones inside the same class, and
    within a class srt/vtt are preferred over json3/ttml/srv*, which need
    conversion.
    """
    wanted = _normalize_langs(langs or [])
    if video_lang:
        wanted.extend(_normalize_langs([video_lang]))
    wanted.extend(DEFAULT_LANG_PRIORITY)

    def candidates(is_auto: bool) -> List[CaptionTrack]:
        return [t for t in tracks if t.is_automatic == is_auto]

    # Two passes: human-only first, then automatic (only if allowed).
    # Each group is ordered best-format-first, so a match is also the
    # cheapest format to convert.
    passes = [sorted(candidates(False), key=_format_rank)]
    if allow_automatic:
        passes.append(sorted(candidates(True), key=_format_rank))

    for group in passes:
        for lang in wanted:
            for track in group:
                if _lang_key(track.lang) == lang:
                    return track
    return None


def _normalize_langs(langs: List[str]) -> List[str]:
    """`['pt-BR', 'EN-us']` -> `['pt', 'en']`, keeping order, dropping dupes."""
    out: List[str] = []
    for lang in langs:
        key = _lang_key(lang)
        if key and key not in out:
            out.append(key)
    return out


def _lang_key(lang: str) -> str:
    """Base language of a YouTube tag: `pt-BR` and `pt-BR-orig` -> `pt`."""
    key = (lang or "").lower().split("-")[0].strip()
    # YouTube uses the `-orig` / `-tmt` suffixes for the original track and
    # machine translations of the same audio; they are still the base lang.
    return key


def _format_rank(track: CaptionTrack) -> int:
    """Lower is better: prefer formats that need no conversion."""
    return _FORMAT_RANK.get(track.ext, len(_FORMAT_RANK))


_FORMAT_RANK = {"srt": 0, "vtt": 1, "json3": 2, "ttml": 3}


def languages(
    url: str, allow_automatic: bool = False
) -> Dict[str, List[str]]:
    """Caption languages available for a URL, split by kind.

    Returns `{"human": [...], "automatic": [...]}` with base language tags
    (so `pt-BR` and `pt` collapse). Order is YouTube's, which is roughly
    most-recently-added first — useful to show what a video actually has.
    """
    human: List[str] = []
    auto: List[str] = []
    for track in list_captions(url):
        key = _lang_key(track.lang)
        if not key:
            continue
        if track.is_automatic:
            if allow_automatic and key not in auto:
                auto.append(key)
        elif key not in human:
            human.append(key)
    return {"human": human, "automatic": auto}


def _translate_url(track: CaptionTrack) -> str:
    """URL for the chosen track, forcing SRT output when the source is vtt.

    Only vtt has a `fmt=` switch; json3/ttml/srv* URLs are fetched as-is and
    converted afterwards by `_download_track`.
    """
    url = track.url
    if track.ext == "vtt" and "fmt=" in url:
        url = url.split("&fmt=")[0] + "&fmt=srt"
    elif track.ext == "vtt":
        url = url + "&fmt=srt"
    return url


def fetch_captions(
    url: str,
    output_path: str,
    langs: Optional[List[str]] = None,
    allow_automatic: bool = False,
    write=None,
    video_title: str = "",
) -> CaptionResult:
    """Download the best caption track for `url` as SRT to `output_path`.

    `output_path` must be extension-less: the chosen language is appended,
    so `foo` becomes `foo.en.srt`. Returns a `CaptionResult`; on any
    failure the reason explains what happened and nothing is written.

    Args:
        url: YouTube watch/playlist URL.
        output_path: Path without extension to write the SRT to.
        langs: Preferred language codes (ISO-639-1), in order.
        allow_automatic: Permit YouTube's auto-generated captions.
        write: Logging callback (defaults to no-op).
        video_title: Label used in log lines.
    """
    write = write or (lambda *_: None)
    try:
        with yt_dlp.YoutubeDL(_base_opts()) as ydl:
            info = ydl.extract_info(url, download=False)
    except Exception as e:
        return CaptionResult(ok=False, reason=f"Could not read video info: {e}")
    if not info:
        return CaptionResult(ok=False, reason="No video info returned")

    label = video_title or info.get("title") or url
    tracks = _tracks_from_info(info)

    if not tracks:
        write(f"No captions listed for '{label}'")
        return CaptionResult(ok=False, reason="No captions available")

    video_lang = (info.get("language") or "").split("-")[0] or None
    track = _pick_track(tracks, langs, allow_automatic, video_lang)
    if track is None:
        auto_only = all(t.is_automatic for t in tracks)
        reason = (
            "Only automatic captions available (use --fetch-auto)"
            if auto_only
            else "No caption track matched the requested languages"
        )
        write(f"{reason} for '{label}'")
        return CaptionResult(ok=False, reason=reason, available=tracks)

    kind = "automatic" if track.is_automatic else "human"
    write(f"Found {kind} '{track.lang}' captions for '{label}'. Downloading...")

    # Track URL is fetched directly: yt-dlp's subtitle download path also
    # downloads the video, and we already have the URL in metadata.
    out = f"{output_path}.{track.lang}.srt"
    fetched = _download_track(_translate_url(track), out, ext=track.ext)
    if not fetched:
        return CaptionResult(
            ok=False,
            reason=f"Caption download failed for '{track.lang}'",
            available=tracks,
        )

    return CaptionResult(
        ok=True,
        path=out,
        lang=track.lang,
        automatic=track.is_automatic,
        available=tracks,
    )


def _download_track(track_url: str, out_path: str, ext: str = "") -> bool:
    """Fetch one caption URL to disk, converting to SRT as needed.

    Conversion is chosen by what actually arrived, not by the advertised
    extension: YouTube serves `fmt=srt` requests as srt, but the same URL
    without that parameter can return JSON (json3) or TTML.
    """
    try:
        import urllib.request

        req = urllib.request.Request(
            track_url, headers={"User-Agent": "Mozilla/5.0"}
        )
        with urllib.request.urlopen(req, timeout=60) as resp:
            payload = resp.read()
    except Exception:
        return False

    text = payload.decode("utf-8", errors="replace")
    head = text.lstrip()[:200]
    if head.startswith("WEBVTT"):
        text = _vtt_to_srt(text)
    elif head.startswith("{") or head.startswith("["):
        text = _json3_to_srt(text)
    elif "<tt" in head or head.startswith("<?xml"):
        text = _ttml_to_srt(text)

    try:
        with open(out_path, "w", encoding="utf-8") as handle:
            handle.write(text)
    except OSError:
        return False
    return True


def _ttml_to_srt(ttml: str) -> str:
    """Convert a YouTube TTML payload to SubRip.

    Structure confirmed against YouTube's output:
    `<p begin="00:00:19.514" end="00:00:21.226" style="s2">text<br />more</p>`.
    `<br />` is a line break inside one cue, and entities are XML-escaped.
    """
    import html
    import re

    out: List[str] = []
    index = 0
    for match in re.finditer(
        r'<p\b[^>]*\bbegin="([^"]+)"[^>]*\bend="([^"]+)"[^>]*>(.*?)</p>',
        ttml,
        re.DOTALL | re.IGNORECASE,
    ):
        start, end, body = match.groups()
        text = re.sub(r"<br\s*/?>", "\n", body, flags=re.IGNORECASE)
        text = re.sub(r"<[^>]*>", "", text)
        text = html.unescape(text).strip()
        if not text:
            continue
        index += 1
        out.append(str(index))
        out.append(f"{_ttml_time(start)} --> {_ttml_time(end)}")
        out.append(text)
        out.append("")
    return "\n".join(out)


def _ttml_time(value: str) -> str:
    """`00:00:19.514` -> `00:00:19,514`; already-comma input passes through."""
    text = value.strip()
    if "." in text:
        text = text.replace(".", ",", 1)
    return text


def _json3_to_srt(payload: str) -> str:
    """Convert a YouTube json3 caption payload to SubRip.

    Structure confirmed against YouTube's output: `events` is a list of
    `{"tStartMs": int, "dDurationMs": int, "segs": [{"utf8": text}]}`.
    `segs` may hold several fragments (one per word span) and a cue's text
    can contain a real newline for an on-screen line break.
    """
    import json

    try:
        data = json.loads(payload)
    except Exception:
        return ""
    events = data.get("events") or []
    out: List[str] = []
    index = 0
    for event in events:
        start = event.get("tStartMs")
        duration = event.get("dDurationMs")
        if start is None or duration is None:
            continue
        parts = [
            seg.get("utf8", "")
            for seg in (event.get("segs") or [])
            if isinstance(seg, dict) and seg.get("utf8")
        ]
        text = "".join(parts).strip()
        if not text:
            continue
        index += 1
        out.append(str(index))
        out.append(f"{_ms_to_srt(start)} --> {_ms_to_srt(start + duration)}")
        out.append(text)
        out.append("")
    return "\n".join(out)


def _ms_to_srt(ms: int) -> str:
    """Milliseconds since start -> `HH:MM:SS,mmm`."""
    total = max(0, int(ms))
    hours, rem = divmod(total, 3600_000)
    minutes, rem = divmod(rem, 60_000)
    seconds, millis = divmod(rem, 1000)
    return f"{hours:02d}:{minutes:02d}:{seconds:02d},{millis:03d}"


def _vtt_to_srt(vtt: str) -> str:
    """Convert a WebVTT caption payload to SubRip.

    Minimal converter: drops the WEBVTT header and cue identifiers, rewrites
    the timestamp separator from '.' to ',', and strips inline tags. Good
    enough for YouTube's auto-caption payloads, which never carry styling
    blocks beyond the header.
    """
    out: List[str] = []
    cues: List[str] = []
    for raw in vtt.splitlines():
        line = raw.strip()
        if not line or line == "WEBVTT":
            continue
        if line.startswith(("Kind:", "Language:", "NOTE", "STYLE", "REGION")):
            continue
        if line.isdigit() and cues:
            # VTT cue index line; SRT indexes are renumbered below.
            continue
        if "-->" in line:
            # Both separators use '.' in VTT and ',' in SRT.
            head, _, tail = line.partition("-->")
            cues.append(
                f"{head.strip().replace('.', ',')} --> {tail.strip().replace('.', ',')}"
            )
            continue
        if cues:
            # Text line: strip inline tags such as <c> / <00:00:01.000>.
            import re

            cleaned = re.sub(r"<[^>]*>", "", line)
            if cleaned:
                cues.append(cleaned)

    if not cues:
        return ""
    index = 0
    i = 0
    while i < len(cues):
        if "-->" in cues[i]:
            index += 1
            out.append(str(index))
            out.append(cues[i])
            i += 1
            while i < len(cues) and "-->" not in cues[i]:
                out.append(cues[i])
                i += 1
        else:
            i += 1
    return "\n".join(out) + "\n"
